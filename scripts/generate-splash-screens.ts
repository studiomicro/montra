const SCHEMES = ['light', 'dark'] as const;
export type Scheme = (typeof SCHEMES)[number];

/** `--bg` per scheme, as in src/lib/shared/theme.ts. */
const SPLASH_BG: Record<Scheme, string> = { light: '#ffffff', dark: '#111112' };

/** Everything in static/splash/ together stays within this (a unit test checks it). */
export const SPLASH_BUDGET_BYTES = 1_500_000;

export const splashFile = (d: SplashDevice, scheme: Scheme) =>
	`splash/splash-${d.width * d.scale}x${d.height * d.scale}-${scheme}.png`;

/**
 * The icon tile: 32 cells wide (the 512 px icon has 16 px cells), about 30 % of the short side, a whole number
 * of device pixels per cell so Koko's edges stay crisp.
 */
function splashIcon(d: SplashDevice): IconSpec {
	const cell = Math.max(2, Math.round((0.3 * Math.min(d.width, d.height) * d.scale) / 32));
	return { file: '', size: cell * 32, cell, background: 'rounded' };
}

/** The generated table: points, scale and one file per scheme, in the order the head lists them. */
function splashTable(): string {
	const rows = SPLASH_DEVICES.map(
		(d) =>
			`\t{ width: ${d.width}, height: ${d.height}, scale: ${d.scale}, light: '/${splashFile(d, 'light')}', dark: '/${splashFile(d, 'dark')}' }`
	);
	return (
		`// Generated by scripts/generate-splash-screens.ts (node scripts/generate-splash-screens.ts). Do not edit.\n` +
		`// iOS launch images (FN-13b): portrait CSS points, device scale and the file per colour scheme.\n\n` +
		`export interface SplashScreen {\n\twidth: number;\n\theight: number;\n\tscale: 2 | 3;\n\tlight: string;\n\tdark: string;\n}\n\n` +
		`export const SPLASH_SCREENS: readonly SplashScreen[] = [\n${rows.join(',\n')}\n];\n`
	);
}

async function main(root: string) {
	const { chromium } = await import('@playwright/test');
	const dir = join(root, 'static', 'splash');
	rmSync(dir, { recursive: true, force: true });
	mkdirSync(dir, { recursive: true });
	const browser = await chromium.launch();
	let total = 0;
	try {
		const page = await browser.newPage({ deviceScaleFactor: 1 });
		for (const device of SPLASH_DEVICES) {
			const [w, h] = [device.width * device.scale, device.height * device.scale];
			const icon = splashIcon(device);
			const [left, top] = [Math.floor((w - icon.size) / 2), Math.floor((h - icon.size) / 2)];
			for (const scheme of SCHEMES) {
				await page.setViewportSize({ width: w, height: h });
				await page.setContent(
					`<!doctype html><html><body style="margin:0;background:${SPLASH_BG[scheme]}">` +
						`<div style="position:fixed;left:${left}px;top:${top}px">${iconSvg(icon)}</div></body></html>`
				);
				const png = encodeIndexedPng(decodePng(await page.screenshot({ type: 'png' })));
				writeFileSync(join(root, 'static', splashFile(device, scheme)), png);
				total += png.length;
				console.log(`wrote static/${splashFile(device, scheme)} (${png.length} bytes)`);
			}
		}
	} finally {
		await browser.close();
	}
	// Formatted with the repo's Prettier config, so `npm run lint` passes on the generated file as committed.
	const tablePath = join(root, 'src/lib/shared/splash-screens.ts');
	writeFileSync(
		tablePath,
		await format(splashTable(), { ...(await resolveConfig(tablePath)), filepath: tablePath })
	);
	console.log(
		`wrote src/lib/shared/splash-screens.ts; static/splash: ${readdirSync(dir).length} files, ${total} bytes (budget ${SPLASH_BUDGET_BYTES})`
	);
	if (total > SPLASH_BUDGET_BYTES) throw new Error('static/splash exceeds its budget');
}

if (import.meta.main) await main(join(import.meta.dirname, '..'));
