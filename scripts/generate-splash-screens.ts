import { join } from 'node:path';
import { format, resolveConfig } from 'prettier';
import { decodePng, encodeIndexedPng } from './png.ts';
import { iconSvg, type IconSpec } from './generate-mascot-icons.ts';

/**
 * FN-13b: iOS launch images (`<link rel="apple-touch-startup-image">`), light and dark, portrait only. iOS builds no
 * splash screen from the manifest; without an image that matches the device it shows a white screen. Run by hand
 * when Koko changes or Apple ships a new screen size, then commit the outputs; never part of `npm run gates`,
 * `npm run build` or CI:
 *
 *   node scripts/generate-splash-screens.ts
 *
 * Koko's app icon (the same tile as `icons/icon-512.png`) sits centred on `--bg`: `#ffffff` light, `#111112` dark
 * (the values src/lib/shared/theme.ts holds and test/contrast.test.ts checks). Chromium draws each image, then
 * `scripts/png.ts` re-encodes it as a flat-colour indexed PNG (a few KB, no metadata); the same Chromium gives the
 * same bytes. The script also writes the table the root layout and the tests read, `src/lib/shared/splash-screens.ts`.
 *
 * Sizes: CSS points and scale of each iPhone and iPad portrait screen. Apple's HIG "Layout" page lists them, but it
 * renders client-side and was not machine-readable when this was written (2026-10-10), so each row was
 * cross-checked against https://iosref.com/res. Re-check them against the HIG whenever a device is added.
 */

export interface SplashDevice {
	/** CSS pixels, portrait. */
	width: number;
	height: number;
	scale: 2 | 3;
	/** Devices that share the size, for whoever adds the next row. */
	devices: string;
}

