import fs from 'node:fs';
import path from 'node:path';
import type { Adapter, Builder } from '@sveltejs/kit';

/**
 * FN-32: the prerendered public site must answer on the site host only.
 *
 * SvelteKit prerenders the site under its public paths (`/`, `/blog`, `/en/privasi` …). adapter-cloudflare would
 * copy them into the assets directory and its Worker would serve them by path before any routing — on every
 * host, so the app host's `/` would become the landing page. This wrapper hides them from the inner adapter
 * and instead bundles them into the Worker: the generated entry (`_worker.js`) answers them on the site host
 * through src/lib/server/site-static.ts and hands every other request to SvelteKit's own Worker, renamed
 * `_sveltekit_worker.js`. Nothing prerendered is ever a static asset.
 */

export interface SiteFile {
	path: string;
	type: string;
	body: string;
}

/** The generated module holding the prerendered files (a Map of public path → content type and body). */
export function siteFilesModule(files: readonly SiteFile[]): string {
	const entries = files.map(
		(f) =>
			`\t[${JSON.stringify(f.path)}, { type: ${JSON.stringify(f.type)}, body: ${JSON.stringify(f.body)} }]`
	);
	return `// Generated by scripts/site-adapter.ts (FN-32). Do not edit.\nexport default new Map([\n${entries.join(',\n')}\n]);\n`;
}

/** The generated Worker entry: prerendered site files first, then SvelteKit. */
export function workerEntry(
	sveltekitWorker: string,
	siteStatic: string,
	siteFiles: string
): string {
	return [
		'// Generated by scripts/site-adapter.ts (FN-32). Do not edit.',
		`import app from ${JSON.stringify(sveltekitWorker)};`,
		`import { withPrerenderedSite } from ${JSON.stringify(siteStatic)};`,
		`import files from ${JSON.stringify(siteFiles)};`,
		'',
		'export default withPrerenderedSite(app, files);',
		''
	].join('\n');
}

function relativeImport(fromDir: string, target: string): string {
	const rel = path.relative(fromDir, target).split(path.sep).join('/');
	return rel.startsWith('.') ? rel : `./${rel}`;
}

/** Collects every prerendered file; fails the build on anything the Worker could not serve as one. */
function collect(builder: Builder): SiteFile[] {
	const { pages, assets, redirects } = builder.prerendered;
	if (redirects.size > 0)
		throw new Error(`site-adapter: prerendered redirects are not served: ${[...redirects.keys()]}`);
	const dir = path.join(builder.getBuildDirectory('output'), 'prerendered', 'pages');
	const read = (file: string) => fs.readFileSync(path.join(dir, file), 'utf8');
	return [
		...[...pages].map(([p, { file }]) => ({
			path: p,
			type: 'text/html; charset=utf-8',
			body: read(file)
		})),
		// `__data.json` is SvelteKit's client-navigation data; the site ships no JavaScript (csr = false).
		...[...assets]
			.filter(([p]) => !p.endsWith('/__data.json'))
			.map(([p, { type }]) => ({ path: p, type, body: read(p.slice(1)) }))
	];
}

export function withPrerenderedSiteAdapter(inner: Adapter): Adapter {
	return {
		...inner,
		async adapt(builder) {
			const files = collect(builder);
			const hidden = new Proxy(builder, {
				get(target, prop, receiver) {
					if (prop === 'prerendered')
						return { pages: new Map(), assets: new Map(), redirects: new Map(), paths: [] };
					if (prop === 'writePrerendered') return () => [];
					return Reflect.get(target, prop, receiver);
				}
			});
			await inner.adapt(hidden);

			// The inner adapter wrote its Worker to wrangler.jsonc's `main` and the assets next to it.
			const assetsDir = path.resolve(builder.getBuildDirectory('cloudflare'));
			const entry = path.join(assetsDir, '_worker.js');
			const sveltekit = path.join(assetsDir, '_sveltekit_worker.js');
			fs.renameSync(entry, sveltekit);
			fs.appendFileSync(path.join(assetsDir, '.assetsignore'), '\n_sveltekit_worker.js\n');

			const siteDir = path.resolve(builder.getBuildDirectory('cloudflare-site'));
			fs.rmSync(siteDir, { recursive: true, force: true });
			fs.mkdirSync(siteDir, { recursive: true });
			const filesModule = path.join(siteDir, 'files.js');
			fs.writeFileSync(filesModule, siteFilesModule(files));
			fs.writeFileSync(
				entry,
				workerEntry(
					relativeImport(assetsDir, sveltekit),
					relativeImport(assetsDir, path.resolve('src/lib/server/site-static.ts')),
					relativeImport(assetsDir, filesModule)
				)
			);
			builder.log.minor(
				`site-adapter: ${files.length} prerendered site files bundled into the Worker`
			);
		}
	};
}
